import sys, glob
seen = set(); rows = {1: [], 2: [], 3: []}
for f in sorted(glob.glob(sys.argv[1] + '/puzzles*.txt')):
    for line in open(f):
        line = line.strip()
        if not line: continue
        n, fen, mv = line.split('|')
        key = ' '.join(fen.split()[:2])
        if key in seen: continue
        seen.add(key); rows[int(n)].append(fen)
out = ['// Generated by tools/puzzles: positions from engine games, each with a forced mate',
       '// confirmed by the engine. Mate in one positions have exactly one mating move.', '',
       'struct Puzzle: Identifiable, Hashable {', '    let id: String', '    let mateIn: Int', '    let fen: String', '',
       '    static let all: [Puzzle] = [']
for n in (1, 2, 3):
    # fewer pieces first: easier to see
    fens = sorted(rows[n], key=lambda f: sum(c.isalpha() for c in f.split()[0]))
    for i, fen in enumerate(fens):
        out.append(f'        Puzzle(id: "m{n}-{i + 1}", mateIn: {n}, fen: "{fen}"),')
out += ['    ]', '}', '']
open(sys.argv[2], 'w').write('\n'.join(out))
print({k: len(v) for k, v in rows.items()})
